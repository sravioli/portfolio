using System.Text;
using System.Text.Json;
using Srv.Portfolio.ContentGenerator;
using Srv.Portfolio.Rendering;
using Srv.Portfolio.Services;

if (args is ["--verify-readmes", var snapshotDirectory])
{
    await RunSnapshotCommandAsync(() => ReadmeSnapshotGenerator.VerifyAsync(snapshotDirectory));
    return;
}

if ((args.Length == 2 && args[0] == "--readmes") ||
    (args.Length == 4 && args[0] == "--readmes" && args[2] == "--source-directory"))
{
    using var client = new HttpClient { Timeout = TimeSpan.FromSeconds(30) };
    await RunSnapshotCommandAsync(() => ReadmeSnapshotGenerator.GenerateAsync(args[1], (entry, cancellationToken) =>
        args.Length == 4
            ? File.ReadAllTextAsync(Path.Combine(args[3], entry.Repository + ".md"), cancellationToken)
            : client.GetStringAsync(GitHubUrls.RawFile(entry.Repository, entry.ReadmePath!), cancellationToken)));
    return;
}

if (args.Length != 1)
{
    throw new ArgumentException("Provide the generated C# output path, or --readmes <wwwroot> [--source-directory <fixtures>].");
}

var html = new MarkdownRenderer().Render(RootReadmeContent.Source, PortfolioCatalog.RootEntry);
var generated = $$"""
    // <auto-generated />
    namespace Srv.Portfolio.Services;

    internal static class RootReadmeHtml
    {
        internal const string Value = {{JsonSerializer.Serialize(html)}};
    }

    """;
var output = Path.GetFullPath(args[0]);
Directory.CreateDirectory(Path.GetDirectoryName(output)!);
if (!File.Exists(output) || File.ReadAllText(output) != generated)
{
    File.WriteAllText(output, generated, new UTF8Encoding(false));
}

static async Task RunSnapshotCommandAsync(Func<Task> command)
{
    try
    {
        await command().ConfigureAwait(false);
    }
    catch (Exception exception) when (exception is IOException or HttpRequestException or JsonException)
    {
        Console.Error.WriteLine($"error: README snapshot generation/validation failed: {exception.Message}");
        Environment.ExitCode = 1;
    }
}
